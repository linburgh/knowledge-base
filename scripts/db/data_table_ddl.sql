-- PostgreSQL 16 + pgvector DDL for knowledge-base.
-- DDL is intentionally centralized in this file.

create extension if not exists vector;

create table if not exists t_user (
    id bigint generated by default as identity primary key,
    username varchar(128) not null,
    email varchar(255),
    phone varchar(32),
    display_name varchar(128) not null default '',
    avatar varchar(1024),
    password_hash varchar(255),
    external_subject varchar(255),
    status varchar(32) not null default 'active',
    last_login_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (username)
);

create unique index if not exists uk_t_user_email on t_user (email) where email is not null;

create unique index if not exists uk_t_user_external_subject on t_user (external_subject) where external_subject is not null;

create index if not exists idx_t_user_status on t_user (status);

create table if not exists t_login_log (
    id bigint generated by default as identity primary key,
    user_id bigint,
    login_account varchar(255) not null,
    login_type varchar(32) not null,
    result varchar(32) not null,
    failure_reason varchar(64),
    ip_address varchar(64),
    user_agent varchar(1024),
    request_id varchar(128),
    created_at timestamptz not null default now()
);

create index if not exists idx_t_login_log_user_created on t_login_log (user_id, created_at);

create index if not exists idx_t_login_log_account_created on t_login_log (login_account, created_at);

create index if not exists idx_t_login_log_result_created on t_login_log (result, created_at);

create table if not exists t_platform_role (
    id bigint generated by default as identity primary key,
    code varchar(64) not null,
    name varchar(128) not null,
    description varchar(500) not null default '',
    status varchar(32) not null default 'active',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (code)
);

create index if not exists idx_t_platform_role_status on t_platform_role (status);

create table if not exists t_platform_user_role (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    role_id bigint not null,
    created_at timestamptz not null default now(),
    created_by bigint,
    unique (user_id, role_id)
);

create index if not exists idx_t_platform_user_role_user_id on t_platform_user_role (user_id);

create index if not exists idx_t_platform_user_role_role_id on t_platform_user_role (role_id);

create table if not exists t_tenant (
    id bigint generated by default as identity primary key,
    code varchar(64) not null,
    name varchar(255) not null,
    logo varchar(1024),
    contact_name varchar(128),
    contact_email varchar(255),
    status varchar(32) not null default 'active',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (code)
);

create index if not exists idx_t_tenant_status on t_tenant (status);

create table if not exists t_tenant_member (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null,
    user_id bigint not null,
    role_code varchar(64) not null,
    is_primary boolean not null default false,
    status varchar(32) not null default 'active',
    joined_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (tenant_id, user_id)
);

create index if not exists idx_t_tenant_member_tenant_status on t_tenant_member (tenant_id, status);

create index if not exists idx_t_tenant_member_user_id on t_tenant_member (user_id);

create index if not exists idx_t_tenant_member_tenant_role on t_tenant_member (tenant_id, role_code);

create unique index if not exists uk_t_tenant_member_active_owner on t_tenant_member (tenant_id) where role_code = 'tenant_owner' and status = 'active';

create table if not exists t_organization (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null,
    parent_id bigint,
    code varchar(64) not null,
    name varchar(255) not null,
    leader_user_id bigint,
    status varchar(32) not null default 'active',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (tenant_id, code),
    unique (tenant_id, id),
    foreign key (tenant_id, parent_id) references t_organization (tenant_id, id)
);

create index if not exists idx_t_organization_tenant_parent on t_organization (tenant_id, parent_id);

create index if not exists idx_t_organization_tenant_status on t_organization (tenant_id, status);

create table if not exists t_organization_member (
    id bigint generated by default as identity primary key,
    organization_id bigint not null,
    user_id bigint not null,
    role_code varchar(64) not null,
    is_primary boolean not null default false,
    status varchar(32) not null default 'active',
    joined_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (organization_id, user_id)
);

create index if not exists idx_t_organization_member_organization_status on t_organization_member (organization_id, status);

create index if not exists idx_t_organization_member_user_id on t_organization_member (user_id);

create table if not exists t_knowledge_base (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null,
    organization_id bigint,
    name varchar(255) not null,
    description varchar(500) not null default '',
    owner_id varchar(128) not null,
    visibility varchar(32) not null,
    embedding_model varchar(128) not null,
    chunk_size integer not null,
    chunk_overlap integer not null,
    retrieval_top_k integer not null,
    system_prompt text not null default '',
    system_prompt_version integer not null default 1,
    system_prompt_updated_at timestamptz not null default now(),
    created_by bigint not null,
    status varchar(32) not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    foreign key (tenant_id, organization_id) references t_organization (tenant_id, id)
);

create index if not exists idx_t_knowledge_base_owner_id on t_knowledge_base (owner_id);

create index if not exists idx_t_knowledge_base_status on t_knowledge_base (status);

alter table t_knowledge_base add column if not exists system_prompt text not null default '';
alter table t_knowledge_base add column if not exists system_prompt_version integer not null default 1;
alter table t_knowledge_base add column if not exists system_prompt_updated_at timestamptz not null default now();
alter table t_knowledge_base add column if not exists tenant_id bigint;
alter table t_knowledge_base add column if not exists organization_id bigint;
alter table t_knowledge_base add column if not exists created_by bigint;

-- Existing databases must backfill tenant_id and created_by before these columns can be made mandatory.
alter table t_knowledge_base alter column tenant_id set not null;
alter table t_knowledge_base alter column created_by set not null;

create index if not exists idx_t_knowledge_base_tenant_id on t_knowledge_base (tenant_id);

create index if not exists idx_t_knowledge_base_organization_id on t_knowledge_base (organization_id);

create table if not exists t_knowledge_base_prompt (
    id bigint generated by default as identity primary key,
    kb_id bigint not null,
    version integer not null,
    system_prompt text not null,
    created_by varchar(128) not null,
    created_at timestamptz not null default now(),
    unique (kb_id, version)
);

create index if not exists idx_t_knowledge_base_prompt_kb_version on t_knowledge_base_prompt (kb_id, version);

create table if not exists t_document (
    id bigint generated by default as identity primary key,
    kb_id bigint not null,
    source_type varchar(32) not null,
    source_name varchar(512) not null,
    source_uri text,
    content_type varchar(128) not null,
    object_path varchar(1024) not null,
    file_size bigint not null default 0,
    content_hash varchar(128) not null,
    parser varchar(128),
    status varchar(32) not null,
    error_message text,
    created_by varchar(128) not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists idx_t_document_kb_status on t_document (kb_id, status);

create index if not exists idx_t_document_content_hash on t_document (content_hash);

create index if not exists idx_t_document_created_by on t_document (created_by);


create table if not exists t_document_chunk (
    id bigint generated by default as identity primary key,
    kb_id bigint not null,
    document_id bigint not null,
    parent_id bigint,
    chunk_index integer not null,
    content text not null,
    content_hash varchar(128) not null,
    source_name varchar(512) not null,
    page integer,
    section varchar(512),
    start_index integer,
    token_count integer,
    metadata jsonb not null default '{}'::jsonb,
    embedding_model varchar(128) not null,
    embedding vector,
    created_at timestamptz not null default now()
);

create index if not exists idx_t_document_chunk_kb_doc on t_document_chunk (kb_id, document_id);

create index if not exists idx_t_document_chunk_kb_index on t_document_chunk (kb_id, chunk_index);

create index if not exists idx_t_document_chunk_content_hash on t_document_chunk (content_hash);

create index if not exists idx_t_document_chunk_metadata_gin on t_document_chunk using gin (metadata);

